import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--enable-webgl'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const sc = (fn, ...a) => page.evaluate(fn, ...a);
await page.goto('http://localhost:3000/?world=adventure&debug&nomobs', { waitUntil: 'load' });
await page.waitForFunction(() => window.__solrift?.isReady?.() && window.__solrift.worldKind() === 'adventure', null, { timeout: 120000 });
await page.evaluate(() => { document.getElementById('overlay').style.display = 'none'; window.__solrift.forceLock(); });
await sc(() => window.__solrift.teleport(2.5, 70, 6.5, 0, 0));
await sleep(2000);
const tobin = (await sc(() => window.__solrift.mobs().filter((m) => m.kind === 'npc'))).find((n) => n.variant === 4);
const gy = await sc(([x, z]) => window.__solrift.surfaceY(x, z), [tobin.x, tobin.z - 1.8]);
await sc(([x, y, z]) => window.__solrift.teleport(x, y, z, 0, 0), [tobin.x, gy + 0.1, tobin.z - 1.8]);
await sleep(800);
await sc(() => window.__solrift.addCoins(500));
await sc((id) => window.__solrift.talkToMob(id), tobin.id);
await page.waitForSelector('[data-testid=shop-panel]', { timeout: 5000 });
await sleep(400);
await page.screenshot({ path: 'screenshots/shop-direct.png' });
await browser.close();
