// Screenshots of the title screen. Usage: node scripts/lookhome.mjs [url] [outDir] [prefix] [width] [height]
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright';
const url = process.argv[2] ?? 'http://localhost:3000';
const outDir = process.argv[3] ?? 'tmp-shots';
const prefix = process.argv[4] ?? 'home';
const width = Number(process.argv[5] ?? 1440);
const height = Number(process.argv[6] ?? 900);
mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width, height } });
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
page.on('console', (m) => m.type() === 'error' && console.log('[err]', m.text().slice(0, 200)));
await page.goto(`${url}/?home`, { waitUntil: 'load' });
await page.waitForSelector('.wow-play');
await page.waitForTimeout(2500);
const shot = (n) => page.screenshot({ path: `${outDir}/${prefix}-${n}.png` }).then(() => console.log('saved', n));
await shot('landing');
const scrollTo = (y) => page.evaluate((y) => document.getElementById('home-layer').scrollTo({ top: y, behavior: 'instant' }), y);
for (const [i, y] of [[1, 900], [2, 1700], [3, 2500], [4, 3300], [5, 4200]]) {
  await scrollTo(y);
  await page.waitForTimeout(1200);
  await shot(`landing-${i}`);
}
await scrollTo(0);
await page.click('.wow-play');
await page.waitForSelector('#who-guest');
await page.waitForTimeout(1500);
await shot('who');
await page.click('#who-guest');
await page.waitForSelector('#char-name');
await page.waitForTimeout(2000);
await shot('creator');
await page.click('#who-continue');
await page.waitForSelector('#class-cards');
await page.click('.cls-card[data-class="mage"]');
await page.waitForTimeout(800);
await shot('class');
await page.click('#class-confirm');
await page.waitForSelector('#home .mode-card');
await page.waitForTimeout(1500);
await shot('play-single');
await page.click('.mode-card[data-mode="hardcore"]');
await page.waitForTimeout(1200);
await shot('play-hardcore');
await page.click('#way-multi');
await page.waitForTimeout(2500);
await shot('play-multi');
await browser.close();
